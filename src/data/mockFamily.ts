// Combine all people for easy access
export const allPeople: Person[] = [
  grandmother,
  grandfather,
  ...children,
  ...spouses,
  ...grandchildren,
];

// Helper function to get person by ID
export const getPersonById = (id: string): Person | undefined => {
  return allPeople.find((person) => person.id === id);
};

// Helper function to get children of a person
export const getChildren = (personId: string): Person[] => {
  const person = getPersonById(personId);
  if (!person) return [];
  return person.childrenIds.map(id => getPersonById(id)).filter(Boolean) as Person[];
};

// Helper function to get spouse of a person
export const getSpouse = (personId: string): Person | null => {
  const person = getPersonById(personId);
  if (!person || !person.spouseId) return null;
  return getPersonById(person.spouseId) || null;
};

// Helper function to get parents of a person
export const getParents = (personId: string): Person[] => {
  const person = getPersonById(personId);
  if (!person) return [];
  return person.parentIds.map(id => getPersonById(id)).filter(Boolean) as Person[];
};
